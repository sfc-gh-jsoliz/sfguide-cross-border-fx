"""Build the hosted no-account example in docs/try/ (run: npm run build:example).

Bundles the seeded CSVs and the captured Sample AI responses into docs/try/data.js,
copies the fonts and logo the guide and example share, and writes docs/.nojekyll so
GitHub Pages serves every file as-is.
"""
import csv
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"


def rows(name, numeric):
    with open(ROOT / "app" / "sample" / name) as f:
        out = list(csv.DictReader(f))
    for r in out:
        for k in numeric:
            r[k] = float(r[k]) if "." in r[k] else int(r[k])
    return out


data = {
    "corridors": rows("corridors.csv", ["base_fx_rate"]),
    "fx": rows("fx_monthly.csv", ["fx_rate"]),
    "volume": rows("volume_monthly.csv", ["cross_border_volume_usd", "txn_count", "settled_local_ccy", "fx_margin_bps", "fx_pnl_usd"]),
    "ai": json.loads((ROOT / "app" / "sample" / "ai.json").read_text()),
}
(DOCS / "try").mkdir(parents=True, exist_ok=True)
(DOCS / "try" / "data.js").write_text("/* Generated by scripts/build_example.py from app/sample/. */\nwindow.CBFX = "
                                     + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
fonts = DOCS / "fonts"
fonts.mkdir(exist_ok=True)
for f in (ROOT / "app" / "static" / "fonts").iterdir():
    shutil.copy(f, fonts / f.name)
(DOCS / ".nojekyll").write_text("")
print("docs/try/data.js written;", len(data["volume"]), "volume rows,", len(data["ai"]["notes"]), "notes,", len(data["ai"]["ask"]), "answers")
