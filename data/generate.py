"""Seeded, deterministic generator for the Cross-Border & FX synthetic book.

Run:  python3 data/generate.py
Writes the CSVs in data/ and app/sample/ and the INSERT block inside
sql/setup.sql (scripts/build_example.py bundles the CSVs for docs/try/). Same seed, same
output, byte for byte. Standard library only.

The drivers and formulas are the original pack's: eight USD corridors over 24
month-ends (Jul 2024 - Jun 2026), linear volume growth, an 8% Nov/Dec holiday
lift, FX margin around a per-corridor base, and an FX path with per-pair drift.
Only the noise source changed: a fixed-seed Python RNG instead of RANDOM(),
so Sample mode and Snowflake hold exactly the same numbers.
"""
import calendar
import csv
import json
import random
import re
from datetime import date
from pathlib import Path

SEED = 20240701
ROOT = Path(__file__).resolve().parent.parent

# corridor_id, origin, dest, currency_pair, base_fx_rate, display name
CORRIDORS = [
    ("COR_USGB", "US", "GB", "USD/GBP", 0.79, "United States → United Kingdom"),
    ("COR_USEU", "US", "DE", "USD/EUR", 0.92, "United States → Germany"),
    ("COR_USMX", "US", "MX", "USD/MXN", 17.20, "United States → Mexico"),
    ("COR_USIN", "US", "IN", "USD/INR", 83.10, "United States → India"),
    ("COR_USCA", "US", "CA", "USD/CAD", 1.36, "United States → Canada"),
    ("COR_USJP", "US", "JP", "USD/JPY", 149.50, "United States → Japan"),
    ("COR_USBR", "US", "BR", "USD/BRL", 5.00, "United States → Brazil"),
    ("COR_USAU", "US", "AU", "USD/AUD", 1.52, "United States → Australia"),
]
# corridor_id: base monthly volume ($M), monthly growth, base margin (bps), monthly FX drift
DRIVERS = {
    "COR_USGB": (420, 0.010, 55, -0.0008),
    "COR_USEU": (610, 0.012, 48, -0.0005),
    "COR_USMX": (380, 0.018, 72, 0.0015),
    "COR_USIN": (290, 0.022, 85, 0.0010),
    "COR_USCA": (350, 0.008, 42, 0.0003),
    "COR_USJP": (260, 0.006, 60, 0.0020),
    "COR_USBR": (210, 0.020, 90, 0.0018),
    "COR_USAU": (180, 0.011, 50, 0.0006),
}
MONTHS = 24


def month_ends():
    out, y, m = [], 2024, 7
    for _ in range(MONTHS):
        out.append(date(y, m, calendar.monthrange(y, m)[1]))
        y, m = (y + 1, 1) if m == 12 else (y, m + 1)
    return out


def build():
    rng = random.Random(SEED)
    months = month_ends()
    fx, vol = [], []
    for cid, _o, _d, pair, base_rate, _n in CORRIDORS:
        base_vol, g, base_bps, drift = DRIVERS[cid]
        for i, me in enumerate(months):
            rate = round(base_rate * (1 + drift * i + rng.randint(-15, 15) / 1000.0), 6)
            v = round(base_vol * 1e6 * (1 + g * i) * (1.08 if me.month in (11, 12) else 1.0)
                      * (1 + rng.randint(-30, 30) / 1000.0))
            bps = round(base_bps + rng.randint(-6, 6), 1)
            fx.append({"currency_pair": pair, "month_end": me.isoformat(), "fx_rate": rate})
            vol.append({
                "corridor_id": cid, "month_end": me.isoformat(),
                "cross_border_volume_usd": v,
                "txn_count": round(v / 2500.0),
                "settled_local_ccy": round(v * rate),
                "fx_margin_bps": bps,
                "fx_pnl_usd": round(v * bps / 10000.0),
            })
    corr = [{"corridor_id": c[0], "origin_country": c[1], "dest_country": c[2],
             "currency_pair": c[3], "base_fx_rate": c[4], "corridor_name": c[5]} for c in CORRIDORS]
    return corr, fx, vol


def write_csv(path, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)


def sql_values(rows, cols):
    def lit(v):
        return f"'{v}'" if isinstance(v, str) else repr(v)
    return ",\n".join("  (" + ", ".join(lit(r[c]) for c in cols) + ")" for r in rows)


def sql_block(corr, fx, vol):
    cc = ["corridor_id", "origin_country", "dest_country", "currency_pair", "base_fx_rate", "corridor_name"]
    fc = ["currency_pair", "month_end", "fx_rate"]
    vc = ["corridor_id", "month_end", "cross_border_volume_usd", "txn_count", "settled_local_ccy",
          "fx_margin_bps", "fx_pnl_usd"]
    return (
        f"-- Generated by data/generate.py (seed {SEED}). Do not edit by hand.\n"
        f"INSERT INTO CROSS_BORDER_CORRIDOR ({', '.join(cc)}) VALUES\n{sql_values(corr, cc)};\n\n"
        f"INSERT INTO CROSS_BORDER_FX_MONTHLY ({', '.join(fc)}) VALUES\n{sql_values(fx, fc)};\n\n"
        f"INSERT INTO CROSS_BORDER_VOLUME_MONTHLY ({', '.join(vc)}) VALUES\n{sql_values(vol, vc)};\n"
    )


def main():
    corr, fx, vol = build()
    for d in (ROOT / "data", ROOT / "app" / "sample"):
        write_csv(d / "corridors.csv", corr)
        write_csv(d / "fx_monthly.csv", fx)
        write_csv(d / "volume_monthly.csv", vol)
    setup = ROOT / "sql" / "setup.sql"
    if setup.exists():
        text = setup.read_text()
        new = re.sub(r"(-- BEGIN GENERATED DATA\n).*?(-- END GENERATED DATA)",
                     lambda m: m.group(1) + sql_block(corr, fx, vol) + m.group(2), text, flags=re.S)
        setup.write_text(new)
    print(f"seed {SEED}: {len(corr)} corridors, {len(fx)} FX rows, {len(vol)} volume rows")


if __name__ == "__main__":
    main()
